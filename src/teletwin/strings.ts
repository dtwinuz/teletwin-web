const KEY_PREFIX = 'TeleTwin';
// Interface languages closer to Russian than to English for most employees
const RUSSIAN_READERS = new Set(['ru', 'uk', 'be', 'kk', 'ky', 'tg']);

export type TeleTwinLocale = 'uz' | 'ru' | 'en';

export function getTeleTwinLocale(langCode?: string): TeleTwinLocale {
  const base = (langCode || 'uz').toLowerCase().split(/[-_]/)[0];
  if (base === 'uz') return 'uz';
  if (RUSSIAN_READERS.has(base)) return 'ru';

  return 'en';
}

// `undefined` for Uzbek and for keys that are not TeleTwin keys: the caller then uses `fallback.strings`
export function getTeleTwinString(langKey: string, langCode?: string) {
  if (!langKey.startsWith(KEY_PREFIX)) return undefined;
  const locale = getTeleTwinLocale(langCode);
  if (locale === 'uz') return undefined;

  return (locale === 'ru' ? RU : EN)[langKey];
}

export const TELETWIN_STRING_TABLES = { ru: RU, en: EN };
