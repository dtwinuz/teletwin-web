#!/usr/bin/env bash
# Pulls a newer Telegram Web A (Ajaxy/telegram-tt) into the TeleTwin fork.
#
# The fork is an orphan import (no shared history with upstream), so `git merge` cannot find a merge base. The
# recorded upstream base (.upstream-base) is passed explicitly instead: `git merge-tree --merge-base` does a real
# 3-way merge (rename detection, conflict markers) of base -> fork and base -> new upstream.
#
#   scripts/upstream-sync.sh                # merge upstream/master
#   scripts/upstream-sync.sh <sha|ref>      # merge a given upstream commit
#   scripts/upstream-sync.sh --hooks        # print every upstream file the fork changes (file: line+count, ...)
#
# Result: branch chore/upstream-sync-<sha7> with the merged tree in the index and working tree, not committed.
# Exit 0 = clean, 2 = conflicts left with markers (listed). Then follow docs/UPSTREAM-SYNC.md.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
base=$(tr -d '[:space:]' < .upstream-base)

# Paths where the fork's version always wins: upstream's build output, its Playwright suite (gitignored here), its CI
# (TeleTwin has its own; package-and-publish.yml must not come back), and the lockfile (regenerated by npm install).
fork_owned=(dist tests .github package-lock.json)

ensure_base() {
  git cat-file -e "$base^{commit}" 2>/dev/null || git fetch --quiet upstream "$base"
}

if [[ ${1:-} == --hooks ]]; then
  ensure_base
  git diff --name-only --diff-filter=M "$base" HEAD -- . ':(exclude)src/teletwin' \
    $(printf ":(exclude)%s " "${fork_owned[@]}") | while read -r f; do
    hunks=$(git diff -U0 "$base" HEAD -- "$f" | sed -nE 's/^@@ -[0-9,]+ \+([0-9]+)(,([0-9]+))? @@.*/\1 \3/p' \
      | awk '{ n = ($2 == "") ? 1 : $2; if (n > 0) { printf "%s%s+%s", sep, $1, n; sep = ", " } }')
    echo "$f: ${hunks:-binary}"
  done
  exit 0
fi

if [[ -n $(git status --porcelain --untracked-files=no) ]]; then
  echo "working tree is not clean" >&2
  exit 1
fi

git fetch --quiet origin teletwin
git fetch --quiet upstream
ensure_base
new=$(git rev-parse "${1:-upstream/master}^{commit}")
if [[ $new == "$base" ]]; then
  echo "already at upstream ${base:0:7}"
  exit 0
fi

branch="chore/upstream-sync-${new:0:7}"
git switch --quiet -c "$branch" origin/teletwin
echo "upstream ${base:0:7} -> ${new:0:7}: merging into $branch"

status=0
out=$(git merge-tree --write-tree --name-only --no-messages --merge-base="$base" HEAD "$new") || status=$?
if [[ $status -gt 1 ]]; then
  echo "git merge-tree failed ($status)" >&2
  exit "$status"
fi
tree=$(head -n1 <<< "$out")
git read-tree --reset -u "$tree"

for path in "${fork_owned[@]}"; do
  # drop what the merge brought under this path (only files of the merged tree, never local ignored files) ...
  git ls-tree -r -z --name-only "$tree" -- "$path" | while IFS= read -r -d '' f; do
    git cat-file -e "HEAD:$f" 2>/dev/null || rm -f -- "$f"
  done
  git rm -r -q --cached --ignore-unmatch -- "$path"
  # ... and put back the fork's version
  if git cat-file -e "HEAD:$path" 2>/dev/null; then
    git checkout HEAD -- "$path"
  fi
done

conflicts=()
while read -r f; do
  [[ -z $f ]] && continue
  skip=0
  for path in "${fork_owned[@]}"; do [[ $f == "$path" || $f == "$path"/* ]] && skip=1; done
  [[ $skip -eq 1 ]] && continue
  if ! git cat-file -e "HEAD:$f" 2>/dev/null && git cat-file -e "$base:$f" 2>/dev/null; then
    # the fork deleted this upstream file on purpose: keep it deleted
    git rm -q --cached --ignore-unmatch -- "$f"
    rm -f -- "$f"
    continue
  fi
  conflicts+=("$f")
done < <(tail -n +2 <<< "$out" | sort -u)

printf '%s\n' "$new" > .upstream-base
git add .upstream-base

if [[ ${#conflicts[@]} -gt 0 ]]; then
  # keep the conflicted files unstaged so `git diff` shows the markers
  git reset -q -- "${conflicts[@]}"
  echo
  echo "${#conflicts[@]} conflict(s): resolve the markers, keep every 'TeleTwin:' hook, then git add:"
  printf '  %s\n' "${conflicts[@]}"
  exit 2
fi
echo "merged cleanly; next: npm install && npm run check && npm test && npm run build:production (docs/UPSTREAM-SYNC.md)"
